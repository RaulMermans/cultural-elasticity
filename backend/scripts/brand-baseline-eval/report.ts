/**
 * Offline Sprint 9B.1 audit report. Reads frozen evidence only: no Qloo, model or database call.
 * Writes docs/sprint-9b1/evidence/ and the SYNTHETIC e2e fixture. Run: pnpm --filter backend eval:brand-baseline:report
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { buildBaselineResult } from "../../src/brand-baseline/research.js";
import { BASELINE_CASES, BRAND } from "../../tests/fixtures/synthetic/brand-baseline-cases.js";
import { integrityChecks, usefulnessChecks } from "./evaluators.js";
import { CANARY_FIXTURES, RECORDED_PROFILE_FIXTURES, replayCanary, replayRecordedProfile, type Replay } from "./replay.js";

const root = new URL("../../../", import.meta.url);
const out = new URL("docs/sprint-9b1/evidence/", root);
mkdirSync(out, { recursive: true });
const write = (url: URL, value: unknown) => writeFileSync(url, `${JSON.stringify(value, null, 1)}\n`);

const synthetic = (id: string) => {
  const item = BASELINE_CASES.find((candidate) => candidate.id === id)!;
  return buildBaselineResult({
    scanId: "00000000-0000-4000-8000-0000000000e1", brandId: "00000000-0000-4000-8000-0000000000e2", brand: BRAND, brandCapturedAt: "2026-10-25T00:00:00.000Z",
    observations: item.observations, startedAt: "2026-10-25T00:00:00.000Z", finishedAt: "2026-10-25T00:01:00.000Z", providerCallCount: 5, recordedOrLive: "recorded", ...(item.incompleteStages ? { incompleteStages: item.incompleteStages } : {}),
  });
};

function summarize(label: string, evidence: string, replay: Pick<Replay, "result" | "observations" | "brand">) {
  const { result } = replay;
  const integrity = integrityChecks(result, replay.observations, replay.brand);
  const usefulness = usefulnessChecks(result);
  return {
    label, evidence, scanStatus: result.scanStatus, audit: result.audit,
    hypotheses: result.territories.map((item) => ({ name: item.name, concept: item.canonicalConcept, facet: item.facet, evidenceStatus: item.evidenceStatus })),
    themes: result.fingerprint.themes.map((theme) => ({ label: theme.label, members: theme.memberIds.length, possibleDuplicates: theme.possibleDuplicateIds.length })),
    discovery: result.discovery,
    integrity: { verdict: integrity.every((check) => check.pass) ? "PASS" : "FAIL", checks: integrity },
    usefulnessDeterministic: usefulness,
  };
}

const replays = [...CANARY_FIXTURES.map(replayCanary), ...RECORDED_PROFILE_FIXTURES.map(replayRecordedProfile)];
const cases = BASELINE_CASES.map((item) => {
  const result = synthetic(item.id);
  return summarize(item.id, "SYNTHETIC", { result, observations: item.observations, brand: { brandQlooId: "syn-brand-case", describeCorrelationId: "syn-describe" } });
});

// Offline performance on bounded inputs: projection time, artifact size, determinism.
const loewe = replayCanary(CANARY_FIXTURES[0]);
const runs = 500;
const heapBefore = process.memoryUsage().heapUsed;
const started = performance.now();
for (let index = 0; index < runs; index += 1) replayCanary(CANARY_FIXTURES[0]);
const elapsed = performance.now() - started;
const performanceReport = {
  note: "Offline, Node " + process.version + ". Includes reading and parsing the frozen fixture on every run.",
  replayRuns: runs,
  meanReplayMs: Number((elapsed / runs).toFixed(3)),
  heapDeltaMb: Number(((process.memoryUsage().heapUsed - heapBefore) / 1_048_576).toFixed(1)),
  derivedArtifactBytes: Buffer.byteLength(JSON.stringify(loewe.result)),
  asRunArtifactBytes: Buffer.byteLength(JSON.stringify(loewe.asRun)),
  deterministic: JSON.stringify(replayCanary(CANARY_FIXTURES[0]).result) === JSON.stringify(loewe.result),
};

write(new URL("loewe-canary-2.derived-0.2.json", out), {
  fixtureType: "derived_offline_projection",
  notice: "LIVE_RECORDED_REPLAY: ce-brand-baseline/0.2 projection of the stored observations of scan b3a92759-2d28-4fdb-aeca-ca7845750f38. Produced offline with no provider call. The stored as-run 0.1 result is unchanged and remains the record of what ran.",
  lineage: { sourceFixture: CANARY_FIXTURES[0], sourceScanId: loewe.result.execution.derivedFrom?.scanId, sourceResultSchema: loewe.result.execution.derivedFrom?.schemaVersion },
  result: loewe.result,
});
write(new URL("audit-report.json", out), {
  generatedBy: "backend/scripts/brand-baseline-eval/report.ts",
  providerCalls: 0, modelCalls: 0,
  liveRecordedReplays: replays.map((replay) => summarize(replay.label, replay.label.includes("canary") ? "LIVE_RECORDED_REPLAY (baseline scan)" : "LIVE_RECORDED_REPLAY (tag profile only, take 20)", replay)),
  syntheticCases: cases,
  performance: performanceReport,
});
write(new URL("backend/tests/fixtures/synthetic/brand-baseline-e2e-v2.json", root), {
  fixtureType: "synthetic",
  notice: "SYNTHETIC 0.2 results generated by backend/scripts/brand-baseline-eval/report.ts from tests/fixtures/synthetic/brand-baseline-cases.ts.",
  results: { hypotheses: synthetic("luxury-shaped"), zeroTerritory: synthetic("zero-territories-keywords"), insufficient: synthetic("only-operational"), partialProvider: synthetic("degraded-provenance") },
});
console.log(JSON.stringify({ replays: replays.length, cases: cases.length, integrityFailures: [...cases, ...replays.map((replay) => summarize(replay.label, "", replay))].filter((item) => item.integrity.verdict !== "PASS").length, performance: performanceReport }));
